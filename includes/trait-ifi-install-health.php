<?php
/**
 * IFI_Install_Health_Trait — installation structure checks for Inquiry Form Inbox.
 *
 * WordPress's install screen builds its "Activate Plugin" link from the plugin folder it
 * just unpacked. If that folder contains more than one plugin header (a stale 2.x file, a
 * second copy, a renamed main file), the link can point at the wrong file and fail with
 * "The plugin does not have a valid header." — while Plugins → Installed Plugins still
 * works because it rescans the folder.
 *
 * This check only reports the condition on the plugin's own screens. It never deletes
 * files and never changes the install-screen link (that link is generated by WordPress).
 *
 * @package Inquiry_Form_Inbox
 */

defined( 'ABSPATH' ) || exit;

trait IFI_Install_Health_Trait {

	/**
	 * Warn when the plugin folder has a structure that confuses the install screen.
	 */
	public static function install_health_notice(): void {
		if ( ! current_user_can( 'manage_options' ) ) {
			return;
		}

		$screen = function_exists( 'get_current_screen' ) ? get_current_screen() : null;
		if ( ! $screen ) {
			return;
		}

		$allowed = array(
			'plugins',
			'edit-' . self::POST_TYPE,
			self::LIST_SLUG . '_page_' . self::TPL_SLUG,
			self::LIST_SLUG . '_page_' . self::SPAM_SLUG,
		);
		if ( ! in_array( $screen->id, $allowed, true ) ) {
			return;
		}

		if ( ! function_exists( 'get_plugins' ) ) {
			require_once ABSPATH . 'wp-admin/includes/plugin.php';
		}

		$basename = plugin_basename( IFI_PLUGIN_FILE );
		$folder   = dirname( $basename );
		$main     = basename( $basename );

		$issues = array();

		$plugins = get_plugins( '/' . $folder );
		if ( count( $plugins ) > 1 ) {
			$issues[] = sprintf(
				self::t( 'install_health_multi' ),
				implode( ', ', array_keys( $plugins ) )
			);
		}

		if ( 'inquiry-form-inbox.php' !== $main ) {
			$issues[] = sprintf( self::t( 'install_health_main' ), $main );
		}

		if ( ! $issues ) {
			return;
		}
		?>
		<div class="notice notice-warning">
			<p><strong><?php echo esc_html( self::t( 'install_health_title' ) ); ?></strong></p>
			<?php foreach ( $issues as $issue ) : ?>
				<p><?php echo esc_html( $issue ); ?></p>
			<?php endforeach; ?>
		</div>
		<?php
	}
}
